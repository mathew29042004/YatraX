const DICTS: Record<Lang, Dict> = { en, hi, ta, ml, te };
const KEY = "yatrax:lang";

type Vars = Record<string, string | number>;
type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: string, vars?: Vars) => string };

function translate(lang: Lang, key: string, vars?: Vars): string {
  let s = DICTS[lang][key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

const I18nContext = createContext<Ctx>({ lang: "en", setLang: () => undefined, t: (k, v) => translate("en", k, v) });

/** Holds the chosen language (remembered on this device) and sets the page's lang attribute. */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    try {
      const saved = localStorage.getItem(KEY) as Lang | null;
      if (saved && saved in DICTS) setLangState(saved);
    } catch {
      // storage blocked: stay in English
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(KEY, l);
    } catch {
      // not remembered, but still applied
    }
  }, []);
  const t = useCallback((key: string, vars?: Vars) => translate(lang, key, vars), [lang]);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

/** The current language and its translator; outside a provider it's English. */
export function useT() {
  return useContext(I18nContext);
}

/** A compact language switcher, labelled in each language's own script. */
export function LanguagePicker({ className = "" }: { className?: string }) {
  const { lang, setLang, t } = useT();
  return (
    <select
      aria-label={t("lang.label")}
      title={t("lang.label")}
      value={lang}
      onChange={(e) => setLang(e.target.value as Lang)}
      className={`h-8 rounded-md border border-line bg-surface px-1.5 text-xs text-ink ${className}`}
    >
      {LANGS.map((l) => (
        <option key={l.code} value={l.code} lang={l.code}>
          {l.name}
        </option>
      ))}
    </select>
  );
}
